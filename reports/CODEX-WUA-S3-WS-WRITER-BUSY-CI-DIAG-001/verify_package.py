def ref(path):
    data=path.read_bytes();return dict(path=path.relative_to(ROOT).as_posix(),size=len(data),sha256=hashlib.sha256(data).hexdigest())
baseline=json.loads((REPORT/'evidence/baseline.json').read_text(encoding='utf-8'))
if a.phase!='manifest':
    current=[ref(path) for name in ['.ultra','Чат_pro','Чат_Pro_01','.obsidian'] for path in (ROOT/name).rglob('*') if path.is_file()]
    old={v['path']:v for v in baseline['protected']};new={v['path']:v for v in current}
    changes=[dict(path=k,before=old.get(k),after=new.get(k)) for k in sorted(old.keys()|new.keys()) if old.get(k)!=new.get(k)]
    sources=[]
    for v in baseline['source']:
        backup=REPORT/'before'/(v['path']+'.source.txt');assert hashlib.sha256(backup.read_bytes()).hexdigest()==v['sha256']
        sources.append(dict(path=v['path'],unchanged=ref(ROOT/v['path'])==v,native_card=a.phase=='after_finish' and v['path']=='Документация/000_Задачи Codex.md'))
    compile_files=[REPORT/'diagnose.py',REPORT/'guard/sitecustomize.py',REPORT/'guard/writer_trace.py']
    for path in compile_files:compile(path.read_text(encoding='utf-8'),str(path),'exec')
    value=dict(utc=dt.datetime.now(dt.timezone.utc).isoformat(),python=sys.version,platform=platform.platform(),source_checks=sources,
               protected_counts=dict(Counter(v['path'].split('/')[0] for v in current)),
               user_storage_changes=[v for v in changes if not v['path'].startswith('.obsidian/')],editor_changes=[v for v in changes if v['path'].startswith('.obsidian/')],
               compile_passed=3,launcher=json.loads((ROOT/'web_alarm/launch_config.json').read_text(encoding='utf-8'))['active'])
