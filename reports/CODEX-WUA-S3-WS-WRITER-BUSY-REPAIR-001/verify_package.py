"""Conservation/diff/compile and manifest. User/editor files are never restored by this tool."""
from pathlib import Path
from collections import Counter
import argparse
import datetime as dt
import difflib
import hashlib
import json
import platform
import sys

REPORT=Path(__file__).resolve().parent;ROOT=REPORT.parents[1]
p=argparse.ArgumentParser();p.add_argument('--phase',choices=['before_finish','after_finish','manifest'],required=True);a=p.parse_args()
OWNED=['context_storage.py','test_ultra_chat_storage.py']
def ref(path):
    data=path.read_bytes();return dict(path=path.relative_to(ROOT).as_posix(),size=len(data),sha256=hashlib.sha256(data).hexdigest())
baseline=json.loads((REPORT/'evidence/baseline.json').read_text(encoding='utf-8'))
if a.phase!='manifest':
    current=[ref(path) for name in ['.ultra','Чат_pro','Чат_Pro_01','.obsidian'] for path in (ROOT/name).rglob('*') if path.is_file()]
    old={v['path']:v for v in baseline['protected']};new={v['path']:v for v in current}
    changes=[dict(path=k,before=old.get(k),after=new.get(k)) for k in sorted(old.keys()|new.keys()) if old.get(k)!=new.get(k)]
    readonly=[]
    for before in baseline['source']:
        name=before['path'];backup=REPORT/'before'/(name+'.source.txt');assert hashlib.sha256(backup.read_bytes()).hexdigest()==before['sha256']
        if name not in OWNED:readonly.append(dict(path=name,unchanged=ref(ROOT/name)==before,native_card=name=='Документация/000_Задачи Codex.md' and a.phase=='after_finish'))
        else:
            text=(ROOT/name).read_text(encoding='utf-8');compile(text,name,'exec')
            diff=''.join(difflib.unified_diff(backup.read_text(encoding='utf-8').splitlines(keepends=True),text.splitlines(keepends=True),fromfile='before/'+name,tofile='after/'+name))
            (REPORT/'evidence'/(name+'.diff.txt')).write_text(diff,encoding='utf-8')
    value=dict(utc=dt.datetime.now(dt.timezone.utc).isoformat(),platform=platform.platform(),python=sys.version,
               protected_counts=dict(Counter(v['path'].split('/')[0] for v in current)),
               user_storage_changes=[v for v in changes if not v['path'].startswith('.obsidian/')],
               editor_changes=[v for v in changes if v['path'].startswith('.obsidian/')],readonly=readonly,baseline_copies_verified=len(baseline['source']),compile_passed=2,
               launcher=json.loads((ROOT/'web_alarm/launch_config.json').read_text(encoding='utf-8'))['active'])
    (REPORT/'evidence'/('conservation_'+a.phase+'.json')).write_text(json.dumps(value,ensure_ascii=False,indent=2),encoding='utf-8');print(json.dumps(value,ensure_ascii=False,indent=2))
    assert not value['user_storage_changes'] and all(v['unchanged'] or v['native_card'] for v in readonly) and value['launcher']=='standard'
else:
    history_path=REPORT/'task_record.json';history=json.loads(history_path.read_text(encoding='utf-8')) if history_path.exists() else None
    files=[ref(path) for path in sorted(REPORT.rglob('*')) if path.is_file() and path.name!='manifest.json']
    value=dict(task_id=REPORT.name,status='BLOCKED / ORIGINAL CI CAUSE OPEN; PARTIAL DIAGNOSTIC REPAIR',history_id=history['history_id'] if history else None,
               independent_review='NOT VERIFIED',publication='LOCAL ONLY; one user publication pending',
               sources=[ref(ROOT/name) for name in OWNED],files=files,
               open=['Original CI physical slowdown and per-lock timing not established','No FIFO/liveness guarantee under arbitrary slow I/O; legitimate busy remains',
                     'Independent CI/portability and existing storage residual risks remain OPEN'],
               native_finish_exception='Unmodified task_slot_rotate.py finish; own card/history artifacts generated by it',self_hash='excluded to avoid circular digest')
    (REPORT/'manifest.json').write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    assert all(ref(ROOT/v['path'])==v for v in files+value['sources'])
    print(json.dumps(dict(files=len(files),sources=2,history_id=value['history_id'],verified=True)))
